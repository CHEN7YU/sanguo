import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { collectReleaseAssets } from './release-assets.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'dist');
const index = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const runtimeFiles = new Set(['index.html']);
for (const match of index.matchAll(/<(?:script|link)\b[^>]*\b(?:src|href)=["']([^"']+)["']/gi)) {
  const filename = match[1].split(/[?#]/)[0];
  if (!/^[A-Za-z0-9_-]+\.(?:m?js|css)$/.test(filename)) {
    throw new Error(`Unsupported runtime reference in index.html: ${match[1]}`);
  }
  runtimeFiles.add(filename);
}
const sources = [...runtimeFiles].map(file => fs.readFileSync(path.join(root, file), 'utf8'));
const files = [...runtimeFiles, ...collectReleaseAssets(sources)].sort();
const limit = 25 * 1024 * 1024;
let bytes = 0;

for (const file of files) {
  const source = path.resolve(root, ...file.split('/'));
  if (!source.startsWith(root + path.sep)) throw new Error(`Invalid release path: ${file}`);
  const stat = fs.lstatSync(source);
  if (!stat.isFile()) throw new Error(`Release source must be a regular file: ${file}`);
  if (stat.size > limit) throw new Error(`Cloudflare asset exceeds 25 MiB: ${file}`);
  if (stat.size < 1024 && fs.readFileSync(source, 'utf8').startsWith('version https://git-lfs.github.com/spec/v1')) {
    throw new Error(`Git LFS content missing: ${file}. Run git lfs pull before building.`);
  }
  bytes += stat.size;
}

// Only a directory previously generated by this script may be replaced.
const marker = '.cloudflare-build';
if (fs.existsSync(output)) {
  if (fs.lstatSync(output).isSymbolicLink() || !fs.existsSync(path.join(output, marker))
      || !fs.lstatSync(path.join(output, marker)).isFile()) {
    throw new Error('Refusing to replace an existing unmanaged dist directory.');
  }
  const wanted = new Set([...files, marker, '.assetsignore'].map(file => path.join(output, ...file.split('/'))));
  function removeStaleFiles(directory) {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const filename = path.join(directory, entry.name);
      if (entry.isSymbolicLink()) throw new Error(`Release output must not contain links: ${filename}`);
      if (entry.isDirectory()) removeStaleFiles(filename);
      else if (!entry.isFile()) throw new Error(`Invalid release output: ${filename}`);
      else if (!wanted.has(filename)) fs.rmSync(filename);
    }
  }
  // Keep directory handles valid for Wrangler's Windows asset watcher.
  removeStaleFiles(output);
} else {
  fs.mkdirSync(output);
}
fs.writeFileSync(path.join(output, marker), 'Generated by tools/build-cloudflare.mjs\n');
fs.writeFileSync(path.join(output, '.assetsignore'), `${marker}\n`);
for (const file of files) {
  const destination = path.join(output, ...file.split('/'));
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.copyFileSync(path.join(root, ...file.split('/')), destination);
}
execFileSync(process.execPath, [path.join(root, 'tools', 'verify_release_assets.mjs'), output], { stdio: 'inherit' });
console.log(`Cloudflare build: ${files.length} runtime files, ${(bytes / 1048576).toFixed(2)} MiB -> ${output}`);
