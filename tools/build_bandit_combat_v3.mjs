import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const require=createRequire(import.meta.url);
const sharp=require('sharp');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const outputDir=path.join(root,'assets','troops','bandit-combat-v3');
const GUTTER=2,COLS=5;

const sources={
  attack:'assets/troops/bandit-attack-v2.webp',
  hurt:'assets/troops/bandit-hurt-v2.webp',
  friendlyAttack:'assets/friendly/bandit-attack-friendly-v2.webp',
  friendlyHurt:'assets/friendly/bandit-hurt-friendly-v2.webp'
};

function keepPrimaryComponent(src,width,height,x0,cellW,dst,dstW,dx0,dy0){
  const count=cellW*height,labels=new Int32Array(count),queue=new Int32Array(count),sizes=[0];let label=0,total=0;
  for(let y=0;y<height;y++)for(let x=0;x<cellW;x++){
    const p=y*cellW+x,alpha=src[(y*width+x0+x)*4+3];if(alpha>2)total++;if(alpha<=2||labels[p])continue;
    label++;let head=0,tail=0,size=0;queue[tail++]=p;labels[p]=label;
    while(head<tail){const q=queue[head++],qy=Math.floor(q/cellW),qx=q-qy*cellW;size++;for(let oy=-1;oy<=1;oy++)for(let ox=-1;ox<=1;ox++){
      if(!ox&&!oy)continue;const nx=qx+ox,ny=qy+oy;if(nx<0||ny<0||nx>=cellW||ny>=height)continue;const next=ny*cellW+nx;if(labels[next]||src[(ny*width+x0+nx)*4+3]<=2)continue;labels[next]=label;queue[tail++]=next
    }}sizes[label]=size
  }
  let primary=0;for(let i=1;i<sizes.length;i++)if(sizes[i]>(sizes[primary]||0))primary=i;
  let minX=cellW,minY=height,maxX=-1,maxY=-1,kept=0;
  for(let y=0;y<height;y++)for(let x=0;x<cellW;x++)if(labels[y*cellW+x]===primary){
    const si=(y*width+x0+x)*4,di=((dy0+y)*dstW+dx0+x)*4;src.copy(dst,di,si,si+4);kept++;minX=Math.min(minX,x);minY=Math.min(minY,y);maxX=Math.max(maxX,x);maxY=Math.max(maxY,y)
  }
  if(!kept)throw new Error(`empty bandit frame at ${x0}`);
  return{bounds:[minX,minY,maxX-minX+1,maxY-minY+1],retained:kept/Math.max(1,total),components:sizes.slice(1).filter(size=>size>=20).length}
}

async function pack(name,source){
  const decoded=await sharp(path.join(root,source)).ensureAlpha().raw().toBuffer({resolveWithObject:true}),{width,height}=decoded.info;
  const starts=Array.from({length:COLS+1},(_,i)=>Math.floor(i*width/COLS)),maxSourceW=Math.max(...starts.slice(0,-1).map((start,i)=>starts[i+1]-start));
  const cellW=maxSourceW+GUTTER*2,cellH=height+GUTTER*2,outW=cellW*COLS,outH=cellH,dst=Buffer.alloc(outW*outH*4),bounds=[];let removed=0,minRetained=1;
  for(let frame=0;frame<COLS;frame++){
    const sourceW=starts[frame+1]-starts[frame],offsetX=GUTTER+Math.floor((maxSourceW-sourceW)/2),stat=keepPrimaryComponent(decoded.data,width,height,starts[frame],sourceW,dst,outW,frame*cellW+offsetX,GUTTER);
    bounds.push([stat.bounds[0]+offsetX,stat.bounds[1]+GUTTER,stat.bounds[2],stat.bounds[3]]);removed+=Math.max(0,stat.components-1);minRetained=Math.min(minRetained,stat.retained)
  }
  if(minRetained<.75)throw new Error(`${name}: retained ratio too low ${minRetained.toFixed(3)}`);
  const file=path.join(outputDir,`${name}.webp`);await sharp(dst,{raw:{width:outW,height:outH,channels:4}}).webp({quality:88,alphaQuality:100,smartSubsample:true}).toFile(file);
  console.log(`${name}: ${width}x${height} -> ${outW}x${outH}; removed ${removed}; retained >= ${(minRetained*100).toFixed(1)}%`);
  return bounds
}

fs.mkdirSync(outputDir,{recursive:true});
const packed={};for(const [name,source] of Object.entries(sources))packed[name]=await pack(name,source);
for(const pair of [['attack','friendlyAttack'],['hurt','friendlyHurt']])if(JSON.stringify(packed[pair[0]])!==JSON.stringify(packed[pair[1]]))throw new Error(`${pair[0]} and ${pair[1]} bounds differ`);
const manifest={attack:{bandit:packed.attack},hurt:{bandit:packed.hurt}};
fs.writeFileSync(path.join(outputDir,'manifest.json'),JSON.stringify(manifest,null,2));
fs.writeFileSync(path.join(root,'bandit-combat-bounds-v3.js'),`// Generated by tools/build_bandit_combat_v3.mjs.\nwindow.BANDIT_COMBAT_CLEAN_BOUNDS=${JSON.stringify(manifest)};\n`);
console.log('bandit combat cleanup complete');
