import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const game=fs.readFileSync(new URL('../game.js',import.meta.url),'utf8');
const start=game.indexOf("  const swornBrotherIds=new Set(['liu','guan','zhang']);");
const end=game.indexOf('  function announceBrotherGuard(',start);
assert.ok(start>=0&&end>start,'桃园护援判定缺失');
const liu={id:'liu',side:'ally',hp:300,maxHp:1000,x:5,y:5,spawnOrder:0};
const guan={id:'guan',side:'ally',hp:400,maxHp:800,x:6,y:6,spawnOrder:1};
const zhang={id:'zhang',side:'ally',hp:700,maxHp:1000,x:4,y:5,spawnOrder:2};
const enemy={id:'enemy',side:'enemy',hp:500,maxHp:500,x:7,y:5};
const context={units:[liu,guan,zhang,enemy],isCriticallyWounded:u=>u.hp>0&&u.maxHp>0&&u.hp/u.maxHp<=.3,isOpponent:(a,b)=>(a.side==='enemy')!==(b.side==='enemy')};
vm.runInNewContext(game.slice(start,end)+';result=brotherGuardFor(units[0],units[3]);',context);
assert.equal(context.result.id,'zhang','两名兄弟都相邻时应由兵力比例更高者护援');
liu.hp=301;vm.runInNewContext('result=brotherGuardFor(units[0],units[3]);',context);assert.equal(context.result,null,'目标高于30%兵力时不应护援');
liu.hp=300;guan.x=8;guan.y=8;zhang.x=8;zhang.y=5;vm.runInNewContext('result=brotherGuardFor(units[0],units[3]);',context);assert.equal(context.result,null,'兄弟不在周围8格内时不应护援');
assert.ok(game.includes('const protectedTarget=t,brotherGuard=brotherGuardFor(protectedTarget,a)'),'普通物理攻击未接入桃园护援');
assert.ok(game.includes('guard=brotherGuardFor(originalTarget,defender)'),'物理反击未接入桃园护援');
assert.ok(game.includes('playBrotherGuardCombatAnimation(a,protectedTarget,brotherGuard'),'敌军护援攻击没有使用原受击格作为交战位置');
assert.ok(game.includes('playBrotherGuardCombatAnimation(defender,originalTarget,guard'),'反击护援没有使用原受击格作为交战位置');
assert.ok(game.includes('guard.x=protectedPosition.x;guard.y=protectedPosition.y;protectedTarget.x=guardPosition.x;protectedTarget.y=guardPosition.y'),'护援动画没有先交换挡枪者与原目标的战场位置');
assert.ok(game.includes('finally{guard.x=guardPosition.x;guard.y=guardPosition.y;protectedTarget.x=protectedPosition.x;protectedTarget.y=protectedPosition.y;draw()}'),'护援动画结束后没有恢复双方位置');
assert.ok(game.includes("if(!a||!t||!inAttackRange(a,t))return false;"),'敌军攻击缺少最终射程校验');
const rangeStart=game.indexOf('  function isBasicAttackOffset(');
const rangeEnd=game.indexOf('  function attackTiles(',rangeStart);
assert.ok(rangeStart>=0&&rangeEnd>rangeStart,'统一基础攻击范围判定缺失');
const rangeContext={};
vm.runInNewContext(game.slice(rangeStart,rangeEnd)+";cardinal=isBasicAttackOffset({troop:'infantry'},1,0);diagonal=isBasicAttackOffset({troop:'infantry'},1,1);",rangeContext);
assert.equal(rangeContext.cardinal,true,'短兵必须能攻击上下左右相邻格');
assert.equal(rangeContext.diagonal,false,'短兵不得攻击斜向格');
assert.ok(game.includes('策略和范围伤害不触发'),'属性面板未说明桃园护援限制');
console.log('Brother guard verified: eight-cell trigger, orthogonal melee range, guarded-position swap and restoration.');
